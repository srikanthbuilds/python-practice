#  FUNCTION : it is a block of code which we can reuse it by calling with that function name. 
# -> defined by using "def" keyword.
# -> it may have multiple parameters or NO parameters.

def happy_birthday(name,age):
    print()
    print(f"Happy birthday to {name}")
    print("Happy birthday to you dear")
    print(f"happy birthday to youuuuu and you are {age} years old!")

happy_birthday("john",20)
happy_birthday("mike",30)
happy_birthday("peter parker",50)