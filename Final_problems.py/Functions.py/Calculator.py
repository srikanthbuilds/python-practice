def add(a,b):
    print("Addition : ",a+b)
def sub(a,b):
    print(f"Subraction : {a-b}")
def mul(a,b):
    print(f"Multiplication : {a*b}")
def division(a,b):
    print(f"Division : {a/b}")
def remainder(a,b):
    print(f"Remainder : {a%b}")
